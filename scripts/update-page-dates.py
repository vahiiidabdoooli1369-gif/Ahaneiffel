#!/usr/bin/env python3
"""Sync date metadata to each file's latest substantive Git change, never to today's date."""
from datetime import date
from html import unescape
from pathlib import Path
import re
import subprocess
import sys
from urllib.parse import unquote, urlparse

ROOT = Path(__file__).resolve().parents[1]
SITE_HOST = "ahaneiffel.top"
AUTO_DATE_COMMIT_PATTERNS = (
    "Update all page and sitemap dates",
    "[date-sync]",
)
PERSIAN_DIGITS = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")


def gregorian_to_jalali(g_date):
    """Convert a Gregorian date to a Jalali (Solar Hijri) YYYY/MM/DD string."""
    gy, gm, gd = g_date.year, g_date.month, g_date.day
    g_days_in_month = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
    j_days_in_month = [31, 31, 31, 31, 31, 31, 30, 30, 30, 30, 30, 29]
    gy -= 1600
    gm -= 1
    gd -= 1
    g_day_no = 365 * gy + (gy + 3) // 4 - (gy + 99) // 100 + (gy + 399) // 400
    for i in range(gm):
        g_day_no += g_days_in_month[i]
    if gm > 1 and ((g_date.year % 4 == 0 and g_date.year % 100 != 0) or g_date.year % 400 == 0):
        g_day_no += 1
    g_day_no += gd
    j_day_no = g_day_no - 79
    j_np = j_day_no // 12053
    j_day_no %= 12053
    jy = 979 + 33 * j_np + 4 * (j_day_no // 1461)
    j_day_no %= 1461
    if j_day_no >= 366:
        jy += (j_day_no - 1) // 365
        j_day_no = (j_day_no - 1) % 365
    jm = 0
    while jm < 11 and j_day_no >= j_days_in_month[jm]:
        j_day_no -= j_days_in_month[jm]
        jm += 1
    jd = j_day_no + 1
    return f"{jy:04d}/{jm + 1:02d}/{jd:02d}"


def last_substantive_change(path):
    """Return the last content-change date, ignoring commits generated by this job."""
    rel = Path(path).resolve().relative_to(ROOT).as_posix()
    command = [
        "git", "log", "-1", "--format=%cs", "--no-renames", "--invert-grep",
    ]
    for pattern in AUTO_DATE_COMMIT_PATTERNS:
        command.append(f"--grep={pattern}")
    command.extend(["--", rel])
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise RuntimeError(f"git log failed for {rel}: {result.stderr.strip()}")
    value = result.stdout.strip()
    if not value:
        return None
    try:
        return date.fromisoformat(value)
    except ValueError:
        return None


def target_for_url(url):
    """Map a canonical site URL to a local HTML/XML file without guessing unknown routes."""
    parsed = urlparse(unescape(url.strip()))
    if parsed.scheme != "https" or parsed.hostname != SITE_HOST:
        return None
    route = unquote(parsed.path or "/").lstrip("/")
    if not route:
        candidates = [ROOT / "index.html"]
    elif route.endswith(".xml"):
        candidates = [ROOT / route]
    elif route.endswith(".html"):
        candidates = [ROOT / route, ROOT / route.rstrip("/") / "index.html"]
    elif route.endswith("/"):
        candidates = [ROOT / route / "index.html"]
    else:
        candidates = [ROOT / route / "index.html", ROOT / route, ROOT / (route + ".html")]
    for candidate in candidates:
        try:
            if candidate.is_file() and candidate.resolve().is_relative_to(ROOT.resolve()):
                return candidate
        except (OSError, ValueError):
            continue
    return None


def replace_page_dates(path, iso_date, jalali_date):
    original = path.read_text(encoding="utf-8")
    updated = re.sub(
        r'("dateModified"\s*:\s*")[^"]+(")',
        lambda m: m.group(1) + iso_date + m.group(2),
        original,
    )
    updated = re.sub(
        r'(<meta\s+[^>]*(?:property|name)=["\'](?:article:modified_time|last-modified|dateModified)["\'][^>]*content=["\'])[^"\']+',
        lambda m: m.group(1) + iso_date,
        updated,
        flags=re.I,
    )
    label_pattern = (
        r'((?:آخرین\s*(?:به‌روزرسانی|بروزرسانی|تغییر)|'
        r'(?:به‌روزرسانی|بروزرسانی)\s*(?:صفحه|محتوا|تاریخ)?|Updated\s*:?)'
        r'\s*(?:[:：\-–]|</[^>]+>\s*)?\s*)'
        r'(?:[۰-۹0-9]{4})[/\-年][۰-۹0-9]{1,2}[/\-月][۰-۹0-9]{1,2}'
    )
    updated = re.sub(
        label_pattern,
        lambda m: m.group(1) + jalali_date.translate(PERSIAN_DIGITS),
        updated,
        flags=re.I,
    )
    if updated != original:
        path.write_text(updated, encoding="utf-8")
        return True
    return False


def replace_sitemap_lastmods(path, date_for_path):
    """Update each sitemap entry from its own target's last substantive change."""
    original = path.read_text(encoding="utf-8")
    block_tag = "sitemap" if re.search(r"<sitemapindex\b", original, re.I) else "url"
    block_re = re.compile(rf"<{block_tag}\b[^>]*>[\s\S]*?</{block_tag}>", re.I)
    loc_re = re.compile(r"<loc>\s*(.*?)\s*</loc>", re.I | re.S)
    lastmod_re = re.compile(r"(<lastmod>)[^<]*(</lastmod>)", re.I)

    def replace_block(match):
        block = match.group(0)
        loc = loc_re.search(block)
        lastmod = lastmod_re.search(block)
        if not loc or not lastmod:
            return block
        target = target_for_url(loc.group(1))
        if target is None:
            return block
        changed = date_for_path(target)
        if changed is None:
            return block
        iso = changed.isoformat()
        return lastmod_re.sub(lambda m: m.group(1) + iso + m.group(2), block, count=1)

    updated = block_re.sub(replace_block, original)
    if updated != original:
        path.write_text(updated, encoding="utf-8")
        return True
    return False


def self_test():
    cases = {
        date(2026, 10, 25): "1405/08/03",
        date(2024, 3, 20): "1403/01/01",
        date(2025, 3, 21): "1404/01/01",
    }
    for value, expected in cases.items():
        actual = gregorian_to_jalali(value)
        if actual != expected:
            raise AssertionError(f"{value}: expected {expected}, got {actual}")
    if target_for_url("https://ahaneiffel.top/") != ROOT / "index.html":
        raise AssertionError("Homepage URL did not map to index.html")
    if target_for_url("https://ahaneiffel.top/guides/steel-inspection-center/") != ROOT / "guides/steel-inspection-center/index.html":
        raise AssertionError("Directory URL mapping failed")
    if target_for_url("https://example.com/") is not None:
        raise AssertionError("External host must not map to a local file")
    print(f"Date conversion and URL mapping self-test passed ({len(cases) + 3} cases).")


def main():
    if "--self-test" in sys.argv:
        self_test()
        return

    cache = {}
    def date_for_path(path):
        key = Path(path).resolve()
        if key not in cache:
            cache[key] = last_substantive_change(key)
        return cache[key]

    changed_files = []
    unmapped = []
    html_files = sorted(
        p for p in ROOT.rglob("*.html")
        if not any(part in {".git", ".github", "node_modules"} for part in p.parts)
    )
    for path in html_files:
        changed = date_for_path(path)
        if changed is None:
            continue
        iso = changed.isoformat()
        jalali = gregorian_to_jalali(changed)
        if replace_page_dates(path, iso, jalali):
            changed_files.append(path.relative_to(ROOT).as_posix())

    sitemap_files = sorted(ROOT.glob("sitemap*.xml"))
    for path in sitemap_files:
        if replace_sitemap_lastmods(path, date_for_path):
            changed_files.append(path.relative_to(ROOT).as_posix())

    print(
        f"Synced factual last-modified metadata for {len(changed_files)} files "
        f"using Git content history; no current-date stamping was performed."
    )
    for item in changed_files:
        print(item)
    if unmapped:
        print(f"Unmapped sitemap URLs left unchanged: {len(unmapped)}")


if __name__ == "__main__":
    main()
